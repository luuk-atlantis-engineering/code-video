"""Cuts the screen takes into one clip per screen scene, timed to the voice-over.

Fill in SCENES below for your film. Each scene is (film start, film end, segments); each segment is
(take, from, to, until): the take's [from, to] seconds are sped up or slowed down so the segment ends at film time
`until`, an anchor in the narration taken from js/times.js (S = sentences, C = scenes, word() = a word's moment).
A segment starts where the previous one ended (the first at the scene's start). Use the marks in takes/<take>.json to
find from and to. Keep each segment's speed between about 0.6x and 1.6x, or the screen looks rushed or frozen.

Output: clips/<scene>.mp4 (30 fps, no sound, exactly the scene's length; the last frame is held if the takes run
short), clips/clips.json, js/clips.js, and the clips as static <video> tags in index.html between
<!-- clips:start (written by tools/cut.py) --> and <!-- clips:end -->. They must stay static tags: HyperFrames only
extracts frames for media written in the HTML, so a video added by script renders frozen on its first frame.

Run from the video folder: python -I tools/cut.py [scene ...]   ($FFMPEG, or ffmpeg on PATH)
"""
import json
import os
import subprocess
import sys

FFMPEG = os.environ.get('FFMPEG', 'ffmpeg')
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

with open(os.path.join(HERE, 'js', 'times.js'), encoding='utf-8') as f:
    src = f.read()
T = json.loads(src[src.index('{'):src.rindex('}') + 1])
S = T['S']
C = T['C']


def word(i, w, lead=0.12):
    """The moment the words w of sentence i (0-based) are spoken, from their place in the sentence's text."""
    s = S[i]
    k = s['t'].index(w)
    return s['s'] + (s['e'] - s['s']) * k / len(s['t']) - lead


# Your film's screen scenes. An example, to replace:
SCENES = {
    # Scene 3: the menu, the form, Create, the result. Starts just before sentence 12, ends just before scene 4.
    # 'scene3': (S[12]['s'] - 0.2, C[3]['s'] - 0.3, [
    #     ('take-3-create', 1.2, 6.2, S[13]['s'] - 0.15),
    #     ('take-3-create', 6.2, 17.6, S[14]['s']),
    #     ('take-3-create', 17.6, 22.0, word(15, 'Create')),
    #     ('take-3-create', 22.6, 29.8, C[3]['s'] - 0.3),
    # ]),
}


def cut(name, start, end, segments):
    takes = []
    for seg in segments:
        if seg[0] not in takes:
            takes.append(seg[0])
    args = [FFMPEG, '-hide_banner', '-loglevel', 'error', '-y']
    for t in takes:
        args += ['-i', os.path.join(HERE, 'takes', t + '.mp4')]
    parts, labels, at, plan = [], [], start, []
    for n, (take, a, b, until) in enumerate(segments):
        length = until - at
        if length <= 0:
            raise SystemExit(f'{name}: segment {n} ends at {until:.2f}, before it starts at {at:.2f}')
        rate = (b - a) / length
        plan.append(f'{take} {a:.2f}-{b:.2f} -> {at:.2f}-{until:.2f} x{rate:.2f}')
        parts.append(f'[{takes.index(take)}:v]trim=start={a}:end={b},setpts=(PTS-STARTPTS)/{rate:.5f},fps=30[v{n}]')
        labels.append(f'[v{n}]')
        at = until
    total = end - start
    graph = ';'.join(parts) + ';' + ''.join(labels) + f'concat=n={len(labels)}:v=1:a=0,tpad=stop_mode=clone:stop_duration=3,trim=duration={total:.3f},format=yuv420p[out]'
    out = os.path.join(HERE, 'clips', name + '.mp4')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    subprocess.run(args + ['-filter_complex', graph, '-map', '[out]', '-an', '-c:v', 'libx264', '-crf', '15', '-preset', 'slow',
                           '-r', '30', out], check=True)
    print(f'{name}: film {start:.2f}-{end:.2f} ({total:.2f} s)')
    for p in plan:
        print('   ', p)
    return {'start': round(start, 3), 'duration': round(total, 3)}


only = sys.argv[1:]
placed = {}
for name, (start, end, segs) in SCENES.items():
    if not only or name in only:
        placed[name] = cut(name, start, end, segs)
clips = {}
if os.path.exists(os.path.join(HERE, 'clips', 'clips.json')):
    with open(os.path.join(HERE, 'clips', 'clips.json'), encoding='utf-8') as f:
        clips = json.load(f)
clips.update(placed)
os.makedirs(os.path.join(HERE, 'clips'), exist_ok=True)
with open(os.path.join(HERE, 'clips', 'clips.json'), 'w', encoding='utf-8') as f:
    json.dump(clips, f, indent=2)
with open(os.path.join(HERE, 'js', 'clips.js'), 'w', encoding='utf-8') as f:
    f.write("// Generated by tools/cut.py: each screen clip's place in the film.\nwindow.CLIPS = " + json.dumps(clips) + ";\n")

with open(os.path.join(HERE, 'index.html'), encoding='utf-8') as f:
    page = f.read()
start_tag, end_tag = '<!-- clips:start (written by tools/cut.py) -->', '<!-- clips:end -->'
if start_tag not in page or end_tag not in page:
    raise SystemExit(f'index.html needs {start_tag} and {end_tag} inside the composition root')
tags = ''.join(
    f'\n      <video id="clip-{n}" class="clip shotvid" src="clips/{n}.mp4" data-start="{c["start"]}" data-duration="{c["duration"]}" muted playsinline preload="auto"></video>'
    for n, c in sorted(clips.items()))
page = page[:page.index(start_tag) + len(start_tag)] + tags + '\n      ' + page[page.index(end_tag):]
with open(os.path.join(HERE, 'index.html'), 'w', encoding='utf-8') as f:
    f.write(page)
